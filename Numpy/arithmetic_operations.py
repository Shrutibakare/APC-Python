import numpy as np

a = np.array([[10, 20], [30, 40]])
b = np.array([[2, 4], [5, 8]])

print("First Matrix:")
print(a)

print("Second Matrix:")
print(b)

print("1. Addition:")
print(a + b)

print("2. Subtraction:")
print(a - b)

print("3. Multiplication:")
print(a * b)

print("4. Division:")
print(a / b)

print("5. Modulus:")
print(a % b)