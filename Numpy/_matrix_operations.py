import numpy as np 
a= np.array([[1,2],[3,4]])
b= np.array([[5,6],[7,8]])

print("Matrix A:")
print(a)

print("Matrix B:")
print(b)

print("Matrix Addition:")
print(a+b)

print("Matrix Subtraction:")
print(a-b)

print("Matrix Multiplication:")
print(np.dot(a,b))

print("Transpose of A:")
print(a.T)





